"""Measure the analytics queries with PROFILE and write docs/benchmarks.md.

Usage:
    python -m scripts.benchmarks.run_benchmarks                 # plans and timings with the current indexes
    python -m scripts.benchmarks.run_benchmarks --compare-index # also drop then recreate the index on Event.date

The comparison drops `event_date`, measures, recreates it and measures again. The index is always recreated.
"""

from __future__ import annotations

import argparse
import statistics
from pathlib import Path

from app.database.connection import get_driver
from app.services.analytics import explain
from app.services.analytics.constants import DEFAULT_END, DEFAULT_SERIES, DEFAULT_START
from app.services.analytics.queries import BENCHMARK_QUERIES

OUTPUT = Path("docs/benchmarks.md")
REPEATS = 5
PARAMS = {
    "series_id": DEFAULT_SERIES,
    "start": DEFAULT_START,
    "end": DEFAULT_END,
    "limit": 20,
    "max_lag": 3,
    "top_moves": 10,
    "theme": None,
}
DROP_INDEX = "DROP INDEX event_date IF EXISTS"
CREATE_INDEX = "CREATE INDEX event_date IF NOT EXISTS FOR (e:Event) ON (e.date)"


def measure(session, query: str) -> dict:
    """Estimated EXPLAIN plan plus PROFILE metrics over warmed, repeated runs."""
    estimated_operators = explain.explain(session, query, **PARAMS)
    session.run(query, **PARAMS).consume()
    runs = [explain.profile(session, query, **PARAMS) for _ in range(REPEATS)]
    return {
        "rows": runs[0]["rows"],
        "db_hits": runs[0]["db_hits"],
        "ms": statistics.median(r["ms"] for r in runs),
        "explain_operators": estimated_operators,
        "profile_operators": runs[0]["operators"],
    }


def measure_all(session) -> dict[str, dict]:
    """Measure every benchmark query."""
    return {name: measure(session, query) for name, query in BENCHMARK_QUERIES.items()}


def table(results: dict[str, dict]) -> str:
    """Markdown table of one measurement round."""
    lines = ["| Query | Rows | DB hits | Median ms |", "|---|---|---|---|"]
    for name, item in results.items():
        lines.append(f"| `{name}` | {item['rows']} | {item['db_hits']} | {item['ms']} |")
    return "\n".join(lines)


def plans(results: dict[str, dict], key: str) -> str:
    """Operators of each estimated or executed plan, including index seeks and scans."""
    return "\n".join(f"- `{name}`: {' > '.join(item[key])}" for name, item in results.items())


def render(with_index: dict, without_index: dict | None) -> str:
    """Build the markdown report."""
    parts = [
        "# Benchmarks",
        "",
        "Generated by `python -m scripts.benchmarks.run_benchmarks`. Median of "
        f"{REPEATS} runs after one warm-up run.",
        "",
        "## With the indexes of `scripts/schema.cypher`",
        "",
        table(with_index),
        "",
        "EXPLAIN estimated plans (the query is not executed):",
        "",
        plans(with_index, "explain_operators"),
        "",
        "PROFILE executed plans (the table above reports their rows and database hits):",
        "",
        plans(with_index, "profile_operators"),
    ]
    if without_index is not None:
        parts += [
            "",
            "## Without the index on `Event.date`",
            "",
            table(without_index),
            "",
            "EXPLAIN estimated plans:",
            "",
            plans(without_index, "explain_operators"),
            "",
            "PROFILE executed plans:",
            "",
            plans(without_index, "profile_operators"),
        ]
        top_events_saved = without_index["top_events"]["db_hits"] - with_index["top_events"]["db_hits"]
        top_countries_extra = with_index["top_countries"]["db_hits"] - without_index["top_countries"]["db_hits"]
        parts += [
            "",
            "## Interpretation",
            "",
            f"The `Event.date` index saves {top_events_saved:,} database hits for `top_events` in this window. "
            "The EXPLAIN and PROFILE plans above show an index seek with the index and a label scan without it.",
            f"For `top_countries`, the indexed plan uses {top_countries_extra:,} more database hits: the measured "
            "window covers nearly every event, so the index is not selective. The other three queries do not depend "
            "on `Event.date`; their nearly identical counts are a control. These small, warmed-run timings describe "
            "this dataset and machine, not a general speedup.",
        ]
    return "\n".join(parts) + "\n"


def main() -> None:
    """Command-line entry point."""
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--compare-index", action="store_true")
    args = parser.parse_args()
    without_index = None
    with get_driver().session() as session:
        with_index = measure_all(session)
        if args.compare_index:
            try:
                session.run(DROP_INDEX).consume()
                without_index = measure_all(session)
            finally:
                session.run(CREATE_INDEX).consume()
    OUTPUT.write_text(render(with_index, without_index), encoding="utf-8")
    print(f"Wrote {OUTPUT}")


if __name__ == "__main__":
    main()
